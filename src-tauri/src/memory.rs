//! Возврат памяти системе. glibc держит освобождённое у себя: после загрузки кэша и
//! скачивания пачек писем процесс оставался на сотнях мегабайт, хотя данные уже были
//! на диске. Поэтому — меньше арен (у каждого потока tokio была своя) и явный trim.

/// В самом начале main, до запуска потоков.
pub fn limit_arenas() {
    #[cfg(target_env = "gnu")]
    // SAFETY: mallopt лишь меняет настройку аллокатора; вызывается до создания потоков.
    unsafe {
        libc::mallopt(libc::M_ARENA_MAX, 2);
    }
}

/// Отдать системе свободные страницы всех арен — после крупных временных выделений.
pub fn trim() {
    #[cfg(target_env = "gnu")]
    // SAFETY: malloc_trim безопасен из любого потока, ничего не освобождает из используемого.
    unsafe {
        libc::malloc_trim(0);
    }
}
